// ─── Translation map ─────────────────────────────────────────────────────────
const translations: Record<LangCode, Translations> = {
  en, tr, es, fr, de, pt, ar, ja, ko, zh,
};

// ─── Active language state (module-level singleton) ──────────────────────────
let _currentLang: LangCode = "en";

export function getCurrentLang(): LangCode {
  return _currentLang;
}

export function setLanguage(code: LangCode) {
  _currentLang = code;
  localStorage.setItem("app-language", code);
  // Update html dir for RTL languages
  const lang = LANGUAGES.find((l) => l.code === code);
  document.documentElement.setAttribute("lang", code);
  document.documentElement.setAttribute("dir", lang?.rtl ? "rtl" : "ltr");
  // Notify subscribers
  _subscribers.forEach((fn) => fn(code));
}

export function getSavedLanguage(): LangCode | null {
  const saved = localStorage.getItem("app-language");
  if (saved && saved in translations) return saved as LangCode;
  return null;
}

export function initLanguage() {
  const saved = getSavedLanguage();
  if (saved) {
    _currentLang = saved;
    const lang = LANGUAGES.find((l) => l.code === saved);
    document.documentElement.setAttribute("lang", saved);
    document.documentElement.setAttribute("dir", lang?.rtl ? "rtl" : "ltr");
  }
}

// ─── Subscription for React re-renders ───────────────────────────────────────
const _subscribers = new Set<(lang: LangCode) => void>();

export function subscribeLanguage(fn: (lang: LangCode) => void) {
  _subscribers.add(fn);
  return () => _subscribers.delete(fn);
}

// ─── Translation function ─────────────────────────────────────────────────────
export function t(key: keyof Translations, lang?: LangCode): string {
  const l = lang ?? _currentLang;
  return (translations[l] as Translations)[key] ?? (translations.en as Translations)[key] ?? key;
}